#!/usr/bin/env python3
"""Generate indexed 320x256 SWOS club-business artwork and five stadium tiers.
Run from the unpacked game's root. Uses the menu palette already built into SWOS.
The files are data/expanded/club_*.raw (palette indices, no SDL/image libs needed at runtime).
"""
from PIL import Image, ImageDraw, ImageFont
from pathlib import Path
import re, math, random

ROOT=Path(__file__).resolve().parents[2]
SRC=ROOT/'sorgenti'
OUT=ROOT/'data'/'expanded'
OUT.mkdir(parents=True,exist_ok=True)
code=(SRC/'src'/'swos_globals.c').read_text()
m=re.search(r'uint16_t _menuPalette\[256\] = \{(.*?)\};',code,re.S)
assert m, 'AGA menu palette not found'
values=[int(x,16) for x in re.findall(r'0x([0-9A-Fa-f]{4})',m.group(1))]
assert len(values)==256,len(values)
PAL=[(((v>>8)&15)*17,((v>>4)&15)*17,(v&15)*17) for v in values]

def nearest(color):
    # Use the game's palette as-is. We never change any palette entries.
    r,g,b=color
    return min(range(1,256),key=lambda i:(PAL[i][0]-r)**2*2+(PAL[i][1]-g)**2*3+(PAL[i][2]-b)**2*2)

# For native pixel-art, the design uses a compact 5x7 font at a 6-pixel advance.
FONT_PATH='/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf'
FONT=ImageFont.truetype(FONT_PATH,9)
GLYPHS=[]
for c in range(32,127):
    g=Image.new('L',(10,12),0)
    d=ImageDraw.Draw(g)
    d.text((0,-1),chr(c),font=FONT,fill=255,stroke_width=0)
    # 5x8 raster from source glyph; crop to a stable cell.
    a=g.crop((0,0,6,8))
    rows=[]
    for yy in range(8):
        mask=0
        for xx in range(5):
            if a.getpixel((xx,yy))>=100: mask|=1<<(4-xx)
        rows.append(mask)
    GLYPHS.append(rows)
font_h=SRC/'src'/'expanded_club_font.h'
font_h.write_text('/* Autogenerated 5x8 glyph rows, ASCII 32..126. Pixel-art labels, not a font file. */\n'
    '#ifndef EXPANDED_CLUB_FONT_H\n#define EXPANDED_CLUB_FONT_H\n'
    'static const unsigned char cb_glyphs[95][8] = {\n'+
    ',\n'.join('    {'+','.join('0x%02X'%v for v in rows)+'} /* %d */'%(i+32) for i,rows in enumerate(GLYPHS))+
    '\n};\n#endif\n')

def ptext(draw,x,y,text,color='#ffffff',shadow='#020817',align='left'):
    text=str(text).upper()
    width=len(text)*6-1
    if align=='center': x-=width//2
    if align=='right': x-=width
    for n,ch in enumerate(text):
        if not (32<=ord(ch)<=126): ch='?'
        rows=GLYPHS[ord(ch)-32]
        for dy,mask in enumerate(rows):
            for dx in range(5):
                if mask & (1<<(4-dx)):
                    if shadow: draw.point((x+n*6+dx+1,y+dy+1),fill=shadow)
                    draw.point((x+n*6+dx,y+dy),fill=color)

def box(d,rect,fill,stroke='#7bb8ff',shadow='#010516',bright='#b5d8ff',edge=2):
    x0,y0,x1,y1=rect
    d.rectangle((x0+1,y0+2,x1+1,y1+2),fill=shadow)
    d.rectangle(rect,fill=fill,outline=stroke,width=1)
    d.line((x0+2,y0+1,x1-2,y0+1),fill=bright,width=1)
    d.line((x0+1,y0+2,x0+1,y1-2),fill='#476cbb',width=1)
    d.line((x0+2,y1-1,x1-1,y1-1),fill='#17386e',width=1)

def coin(d,x,y):
    d.ellipse((x,y,x+9,y+7),fill='#ffb100',outline='#8d4800')
    d.arc((x+1,y+1,x+8,y+6),0,180,fill='#fff576')
    d.line((x+2,y+3,x+7,y+3),fill='#ffe100')

def crowd(d,x,y,w,h,seed):
    rng=random.Random(seed)
    for _ in range(w*h//16):
        xx=x+rng.randrange(w); yy=y+rng.randrange(h)
        d.rectangle((xx,yy,xx+1,yy+1),fill=rng.choice(['#ffb629','#f5cbb3','#eaf3ff','#2f84ff','#ff7c34']))

def icon(d,k,x,y):
    # 32x19 icons, deliberately drawn on a pixel grid.
    if k==0: # weights
        d.rectangle((x+2,y+8,x+30,y+10),fill='#d3e6f8',outline='#202945')
        for xx in (x+5,x+10,x+22,x+27):
            d.rectangle((xx,y+4,xx+3,y+14),fill='#8aa0d5',outline='#182447')
            d.line((xx+1,y+5,xx+1,y+12),fill='#ffffff')
    elif k==1: # training cones
        for xx in (x+2,x+12,x+22):
            d.polygon([(xx+5,y+2),(xx+1,y+14),(xx+10,y+14)],fill='#ff8500')
            d.line((xx+5,y+3,xx+3,y+9),fill='#fff093',width=2)
            d.rectangle((xx,y+14,xx+11,y+16),fill='#bd4b00')
    elif k==2: # binoculars
        for xx in (x+2,x+18):
            d.ellipse((xx,y+4,xx+13,y+16),fill='#152c6c',outline='#d5e5ff',width=1)
            d.ellipse((xx+3,y+7,xx+10,y+13),fill='#24aaff',outline='#06194b',width=1)
            d.point((xx+5,y+8),fill='#ffffff')
        d.rectangle((x+13,y+4,x+19,y+7),fill='#8097d5')
    elif k==3: # bus
        d.rectangle((x+1,y+5,x+30,y+13),fill='#e7efff',outline='#152451')
        d.rectangle((x+4,y+7,x+24,y+10),fill='#2886ff')
        for xx in (x+9,x+15,x+21): d.line((xx,y+7,xx,y+10),fill='#101b44')
        d.rectangle((x+2,y+13,x+30,y+15),fill='#7596d7')
        for xx in (x+7,x+25): d.ellipse((xx,y+13,xx+5,y+18),fill='#020b2a',outline='#aec2eb')
    elif k==4: # first aid
        d.rectangle((x+5,y+4,x+27,y+17),fill='#dcecff',outline='#1c346a')
        d.rectangle((x+12,y+1,x+21,y+5),fill='#dcecff',outline='#1c346a')
        d.rectangle((x+14,y+7,x+18,y+15),fill='#ff2439')
        d.rectangle((x+11,y+9,x+22,y+12),fill='#ff2439')
    elif k==5: # offices
        d.rectangle((x+4,y+4,x+28,y+18),fill='#c0d7ff',outline='#183469')
        d.rectangle((x+3,y+2,x+29,y+5),fill='#7f9dff',outline='#132350')
        for xx in (x+7,x+16,x+23):
            d.rectangle((xx,y+7,xx+5,y+11),fill='#2c89ed',outline='#0b3765')
        d.rectangle((x+15,y+13,x+20,y+18),fill='#163a85')
    else: # youth pitch
        d.polygon([(x+4,y+14),(x+10,y+3),(x+26,y+3),(x+31,y+14)],fill='#248e19',outline='#d2f2b8')
        d.line((x+10,y+3,x+26,y+3),fill='#ffffff')
        d.line((x+18,y+3,x+18,y+14),fill='#ffffff')
        d.rectangle((x+13,y+1,x+22,y+5),outline='#ffffff')
        d.arc((x+12,y+5,x+25,y+13),0,180,fill='#ffffff')

W,H=320,256
bg=Image.new('RGB',(W,H),'#020b25');d=ImageDraw.Draw(bg)
# Jagged old-SWOS map-inspired background, low contrast.
rng=random.Random(1997)
for i in range(19):
    x=rng.randrange(-40,330); y=rng.randrange(-30,250)
    pts=[(x,y)]
    for j in range(6):
        x+=rng.randrange(-21,23); y+=rng.randrange(6,20)
        pts.append((x,y))
    d.line(pts,fill='#0b2355',width=1)
# Top plaque (green, bevel, bright gold).
d.polygon([(93,2),(228,2),(235,22),(85,22)],fill='#011026')
d.polygon([(97,3),(224,3),(230,20),(90,20)],fill='#e7a621')
d.polygon([(100,5),(221,5),(226,18),(94,18)],fill='#277a10')
d.line((101,6,220,6),fill='#83d334',width=1)
d.line((94,18,225,18),fill='#7d3d08',width=2)
# Stadium side panels and fans/board.
box(d,(5,25,79,68),'#0b2455')
box(d,(240,25,314,68),'#0b2455')
box(d,(5,72,79,117),'#0a1b48')
box(d,(240,72,314,117),'#0a1b48')
# Board figures, suit jackets and heads
for xx,skin,jacket in [(19,'#f4b27c','#273e7c'),(38,'#e1a47d','#47475b'),(57,'#e7aa7b','#244b8d')]:
    d.rectangle((xx,57,xx+12,65),fill=jacket,outline='#050e2a')
    d.polygon([(xx+4,57),(xx+8,57),(xx+6,62)],fill='#ffffff')
    d.line((xx+6,59,xx+6,64),fill='#e32633')
    d.rectangle((xx+3,48,xx+9,56),fill=skin,outline='#34231d')
    d.rectangle((xx+2,46,xx+10,48),fill='#30251e')
    d.point((xx+5,51),fill='#08112a')
    d.point((xx+8,51),fill='#08112a')
# Crowd and flags
crowd(d,245,48,64,17,1996)
for xx in (246,292):
    d.line((xx,45,xx+1,59),fill='#ffffff',width=1)
    d.polygon([(xx,45),(xx+14,46),(xx+11,54),(xx,52)],fill='#4d8fff')
    d.line((xx+2,48,xx+10,48),fill='#ffffff',width=2)
# Stadium info progress bar
for i in range(5):
    d.rectangle((11+i*12,108,19+i*12,113),fill='#213b7a',outline='#6c93d6')
# Upgrade button green
box(d,(244,97,310,114),'#277d0b',stroke='#b7f58b',bright='#d8ff9d')
d.line((246,99,307,99),fill='#71d945')
# Seven facility cards.
CARD_X=[7,50,93,136,179,222,265]
for i,x in enumerate(CARD_X):
    box(d,(x,123,x+41,171),'#0a2658',stroke='#75b5f9')
    d.rectangle((x+2,125,x+39,147),fill='#1c6f14')
    d.line((x+3,126,x+38,126),fill='#3eaf24')
    d.line((x+2,149,x+39,149),fill='#477cc1')
    icon(d,i,x+5,127)
    # 5 empty level cells, dynamically filled by the game.
    for j in range(5):
        xx=x+4+j*7
        d.rectangle((xx,163,xx+5,168),fill='#1d2e5a',outline='#86a5d6')
# Finance panel & balance
box(d,(5,177,207,235),'#091b48')
box(d,(211,177,315,235),'#091b48')
d.line((9,190,203,190),fill='#4d85c8')
d.line((215,190,311,190),fill='#4d85c8')
d.line((111,194,111,231),fill='#2c5a9e')
# Finance rows deliberately have no icons: every pixel is reserved for values.
# balance green ribbon
d.rectangle((215,194,311,211),fill='#194c10',outline='#a3e56a')
d.line((217,196,309,196),fill='#48b81e')
# little money sack
d.ellipse((217,197,232,210),fill='#df9d44',outline='#5c3616')
d.rectangle((221,194,228,198),fill='#a65e26')
d.line((220,197,229,197),fill='#f9c97a')
# bottom Back button and rule
box(d,(7,239,60,254),'#be1015',stroke='#ffcfb0',bright='#ffe0b5')
d.polygon([(13,246),(20,242),(20,250)],fill='#ffffff',outline='#6d0c12')
d.line((67,247,313,247),fill='#7f9cc8',width=2)

# stadium source from user-approved preview
ref=Image.open(SRC/'tools'/'club_business_reference.png').convert('RGB')
base=ref.crop((445,118,1210,415))
for level in range(1,6):
    canvas=Image.new('RGB',(154,88),'#020b25');s=ImageDraw.Draw(canvas)
    rng=random.Random(712+level)
    for _ in range(50):
        x=rng.randrange(154); y=rng.randrange(88)
        s.point((x,y),fill=rng.choice(['#07173a','#07173a','#0b2355']))
    # visible footprint grows each tier; no other stadium is selectable.
    sizes=[(110,56),(126,65),(143,75),(153,81),(154,83)]
    w,h=sizes[level-1]
    spr=base.resize((w,h),Image.Resampling.BOX)
    canvas.paste(spr,((154-w)//2, (88-h)//2+2))
    s=ImageDraw.Draw(canvas)
    if level==1:
        # Modest small-ground fencing, no extra floodlights.
        s.line((12,77,141,77),fill='#bad5b2',width=1)
    if level>=3:
        # Larger floodlight towers and upper stand banners.
        for xx in (12,137):
            s.line((xx,24,xx,8),fill='#d1dbe8',width=2)
            s.rectangle((xx-6,6,xx+6,11),fill='#e9f4ff',outline='#354d72')
            for dot in range(xx-4,xx+5,3): s.point((dot,8),fill='#6b8bc5')
    if level>=4:
        # High-capacity arena adds illuminated facade bands.
        s.line((24,64,128,64),fill='#ffca47',width=2)
        s.line((32,69,120,69),fill='#548cff')
        s.rectangle((58,72,96,77),fill='#294785',outline='#c0d7ff')
    if level==5:
        # National showcase roof & giant scoreboard.
        s.polygon([(22,23),(49,12),(112,12),(136,23),(129,28),(45,19)],fill='#a5bddc',outline='#e3efff')
        s.rectangle((65,4,91,12),fill='#0b285f',outline='#ffcf48')
        s.line((69,8,87,8),fill='#3fff68')
    # Quantize to built-in palette. All 154x88 pixels opaque.
    raw=bytes(nearest(c) for c in canvas.getdata())
    (OUT/f'club_stadium_{level}.raw').write_bytes(raw)
    # Visual preview sprite
    palimg=Image.new('RGB',canvas.size);palimg.putdata([PAL[v] for v in raw]);
    palimg.resize((616,352),Image.Resampling.NEAREST).save(OUT/f'club_stadium_{level}_preview.png')

raw=bytes(nearest(c) for c in bg.getdata())
(OUT/'club_business_bg.raw').write_bytes(raw)
quant=Image.new('RGB',(W,H));quant.putdata([PAL[v] for v in raw]);
quant.resize((1280,1024),Image.Resampling.NEAREST).save(OUT/'club_business_base_preview.png')
print('Generated menu background, five stadium tiers, 5x8 font.\n',OUT)
